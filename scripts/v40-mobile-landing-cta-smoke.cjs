const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file),'utf8');
const landing = read('src/pages/LandingPage.tsx');
const css = read('src/website-v40-mobile-landing-header.css');
const main = read('src/main.tsx');
assert.ok(landing.includes('landing-header-inner'), 'mobile header layout hook must exist');
assert.ok(landing.includes('landing-header-actions'), 'header action layout hook must exist');
assert.ok(landing.includes('landing-header-language'), 'language picker layout hook must exist');
assert.ok(landing.includes('landing-start-button'), 'CTA layout hook must exist');
assert.ok(landing.includes('landing-start-label'), 'CTA should keep the full translated text');
assert.ok(landing.includes("loginAs('student')"), 'student CTA remains functional');
assert.ok(landing.includes('t(\'startLearning\')'), 'CTA remains localized');
assert.ok(css.includes('@media (max-width: 540px)'), 'mobile breakpoint defined');
assert.ok(css.includes('grid-template-rows: 42px 44px'), 'two-row mobile header defined');
assert.ok(css.includes('grid-column: 1 / -1'), 'CTA spans the second row');
assert.ok(css.includes('white-space: nowrap'), 'CTA cannot wrap');
assert.ok(css.includes('text-overflow: ellipsis'), 'longer translations cannot overflow');
assert.ok(css.includes('min-height: 44px'), 'CTA minimum touch target is 44px');
assert.ok(main.includes("import './website-v40-mobile-landing-header.css';"), 'mobile fix stylesheet imported');
assert.ok(main.indexOf('website-v40-mobile-landing-header.css') > main.indexOf('website-v39-student-hero-fix.css'), 'new override loads last');
console.log('PASS: mobile landing CTA no-wrap layout, 44px target, accessible labels, translations and student action preserved.');
